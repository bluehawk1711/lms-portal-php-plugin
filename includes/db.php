function sp_column_exists( $table, $column ) {
	global $wpdb;

	$found = $wpdb->get_results( "SHOW COLUMNS FROM `$table` LIKE '" . $column . "'" ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared -- identifiers only.

	return ! empty( $found );
}

/**
 * Rename the offering tables/columns to class, in place.
 *
 * Introduced in schema 1.1: "offering" was renamed to "class" throughout.
 * dbDelta cannot rename tables or columns, so this does it explicitly and is
 * fully idempotent -- each step is skipped when the new name already exists and
 * the old one does not. No data is dropped.
 */
function sp_migrate_offering_to_class() {
	global $wpdb;

	$renames = array(
		'offerings'         => 'classes',
		'teacher_offerings' => 'teacher_classes',
	);

	foreach ( $renames as $old => $new ) {
		$old_table = sp_table( $old );
		$new_table = sp_table( $new );

		if ( sp_table_exists( $old_table ) && ! sp_table_exists( $new_table ) ) {
			$wpdb->query( "RENAME TABLE `$old_table` TO `$new_table`" ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared -- identifiers only.
		}
	}

	// Rename the offering_id column on every table that carries it.
	$tables = array(
		'classes',
		'teacher_classes',
		'enrollments',
		'attendance_sessions',
		'materials',
	);

	foreach ( $tables as $name ) {
		$table = sp_table( $name );

		if ( sp_table_exists( $table ) && sp_column_exists( $table, 'offering_id' ) && ! sp_column_exists( $table, 'class_id' ) ) {
			$wpdb->query( "ALTER TABLE `$table` CHANGE `offering_id` `class_id` bigint(20) unsigned NOT NULL" ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared -- identifiers only.
		}
	}
}

/**
 * Seed `sp_courses` from the Certificate Manager's course table, exactly once.
 *
 * Ids are copied verbatim, so every existing `sp_classes.course_id` keeps
 * pointing at the same course with no value migration: the portal table starts
 * life as a snapshot of the vendor table and is the source of truth from then
 * on. Courses created later in the portal are never written back here.
 *
 * Runs only while the portal copy is empty, so re-running the installer is a
 * no-op and a site that never used Certificate Manager simply starts empty.
 *
 * @return int Number of courses copied.
 */
function sp_migrate_courses_from_vendor() {
	global $wpdb;

	$portal  = sp_table( 'courses' );
	$vendor  = sp_cert_table( 'courses' );

	if ( ! sp_table_exists( $portal ) || ! sp_table_exists( $vendor ) ) {
		return 0;
	}

	$rows = $wpdb->get_results( "SELECT id, name, code FROM {$vendor} ORDER BY id ASC" ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared -- table name from sp_cert_table().

	if ( empty( $rows ) || $wpdb->get_var( "SELECT COUNT(*) FROM {$portal}" ) ) { // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared -- table name from sp_table().
		return 0;
	}

	$copied = 0;

	foreach ( $rows as $course ) {
		$ok = $wpdb->insert(
			$portal,
			array(
				'id'     => (int) $course->id,
				'name'   => trim( (string) $course->name ) ? trim( (string) $course->name ) : 'Untitled course',
				'code'   => $course->code ? (string) $course->code : null,
				'status' => 'active',
			),
			array( '%d', '%s', '%s', '%s' )
		);

		if ( $ok ) {
			++$copied;
		}
	}

	return $copied;
}

/**
 * Run the installer when the stored schema version is behind the code.
 */
function sp_maybe_upgrade() {
	if ( get_option( 'sp_db_version' ) === SP_DB_VERSION ) {
		return;
	}

	sp_install();
}


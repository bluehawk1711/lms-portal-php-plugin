/**
 * Current schema version. Bump this whenever sp_install() changes.
 *
 * 2.0 introduces `sp_courses`: the portal became the source of truth for
 * courses instead of reading the Certificate Manager's table.
 * 2.1 adds the reusable timing sets.
 * 2.2 adds `sp_calendar_events` (holidays/tests that cancel class) and
 * `sp_teacher_attendance` (per-day teacher presence for the auto-absent run).
 * 2.3 adds `sp_curriculum` (the ordered outline of a course) and
 * `sp_curriculum_progress` (which topics each class has covered).
 * 2.4 adds the assignment/exam system: `sp_assignments` (papers and timed
 * exams), `sp_questions` (the per-class question bank), the exam set tables
 * (`sp_assignment_sets`, `sp_assignment_set_questions`) and the per-student
 * attempt tables (`sp_assignment_students`, `sp_assignment_answers`).
 * 2.5 moves the enrolment ID off the profile and onto the enrolment itself: a
 * student sits one course at a time, so each class enrolment carries its own
 * ID. The Certificate Manager is no longer consulted to find a student.
 * 2.6 adds `sp_certificates` -- the portal's certificate records, filled from a
 * configurable field list. The certificate itself (design, QR, PDF, verify page)
 * is generated by the Certificate Manager plugin; these rows are the portal's
 * bookkeeping (eligibility, serial, stored values) and link to it.
 */
define( 'SP_DB_VERSION', '2.6' );

/**
 * Fully qualified table name for one of our tables.
 *
 * @param string $name Table name without prefix, e.g. 'classes'.
 * @return string
 */
function sp_table( $name ) {
	global $wpdb;

	return $wpdb->prefix . 'sp_' . $name;
}


/**
 * Whether the Certificate Manager plugin is present and its tables exist.
 *
 * Cached per request: the SHOW TABLES probe is not cheap and the answer cannot
 * change mid-request.
 *
 * @return bool
 */
function sp_certificate_manager_active() {
	static $available = null;

	if ( null !== $available ) {
		return $available;
	}

	global $wpdb;

	if ( ! function_exists( 'cert_mgr_grade_options' ) ) {
		$available = false;
		return $available;
	}

	$students_table = $wpdb->prefix . 'cert_students';
	$found          = $wpdb->get_var( $wpdb->prepare( 'SHOW TABLES LIKE %s', $students_table ) );

	$available = ( $found === $students_table );
	return $available;
}

/**
 * Certificate Manager table name.
 *
 * @param string $name 'students', 'courses' or 'batches'.
 * @return string
 */
function sp_cert_table( $name ) {
	global $wpdb;

	return $wpdb->prefix . 'cert_' . $name;
}

/**
 * Whether a grade string is one the Certificate Manager will render.
 *
 * Falls back to a sane default when the plugin is inactive so the portal can
 * still display grades it stored earlier.
 *
 * @param string $grade Candidate grade.
 * @return bool
 */
function sp_is_supported_grade( $grade ) {
	$grade = trim( (string) $grade );

	if ( '' === $grade ) {
		return false;
	}

	if ( function_exists( 'cert_mgr_grade_options' ) ) {
		foreach ( cert_mgr_grade_options() as $option ) {
			if ( 0 === strcasecmp( trim( (string) $option ), $grade ) ) {
				return true;
			}
		}

		return false;
	}

	return in_array( strtoupper( $grade ), array( 'A+', 'A', 'B', 'C', 'D' ), true );
}
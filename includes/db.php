/**
 * Create or migrate every table.
 */
function sp_install() {
	require_once ABSPATH . 'wp-admin/includes/upgrade.php';

	sp_migrate_offering_to_class();

	foreach ( sp_schema_statements() as $statement ) {
		dbDelta( $statement );
	}

	// Only once the courses table exists can it be seeded from the vendor.
	sp_migrate_courses_from_vendor();

	// 2.5: the enrolment ID moved from the profile onto each enrolment.
	sp_migrate_enrollment_enroll_ids();

	update_option( 'sp_db_version', SP_DB_VERSION );
}

/**
 * Move `sp_student_profiles.enroll_id` onto the student's enrolments.
 *
 * The profile used to carry a single ID, which only ever described one course.
 * An enrolment now carries its own ID, so the old value is copied across to
 * every enrolment that has none yet. The profile column is left in place (the
 * installer never drops columns) but nothing reads or writes it any more, so a
 * site that has not re-run the installer keeps working until it does.
 *
 * @return int Number of enrolments updated.
 */
function sp_migrate_enrollment_enroll_ids() {
	global $wpdb;

	$profiles  = sp_table( 'student_profiles' );
	$enroll    = sp_table( 'enrollments' );

	if ( ! sp_table_exists( $profiles ) || ! sp_table_exists( $enroll ) ) {
		return 0;
	}

	if ( ! sp_column_exists( $profiles, 'enroll_id' ) ) {
		return 0;
	}

	if ( ! sp_column_exists( $enroll, 'enroll_id' ) ) {
		return 0;
	}

	$updated = (int) $wpdb->query(
		"UPDATE {$enroll} e
		 INNER JOIN {$profiles} p ON p.id = e.profile_id
		 SET e.enroll_id = p.enroll_id
		 WHERE ( e.enroll_id IS NULL OR e.enroll_id = '' )
		   AND p.enroll_id IS NOT NULL
		   AND p.enroll_id <> ''"
	); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared -- table names from sp_table().

	/*
	 * Any enrolment still without an ID gets one generated from its class code
	 * (or a short class reference) plus a sequence, so certificates can always
	 * be issued without a manual step.
	 */
	$classes = sp_table( 'classes' );

	$missing = $wpdb->get_results(
		"SELECT e.id, e.class_id, c.code
		 FROM {$enroll} e
		 LEFT JOIN {$classes} c ON c.id = e.class_id
		 WHERE e.enroll_id IS NULL OR e.enroll_id = ''
		 ORDER BY e.class_id, e.id"
	); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared -- table names from sp_table().

	if ( $missing ) {
		$per_class = array();

		foreach ( $missing as $row ) {
			$base = ! empty( $row->code ) ? strtoupper( (string) $row->code ) : 'C' . (int) $row->class_id;

			if ( ! isset( $per_class[ $row->class_id ] ) ) {
				$per_class[ $row->class_id ] = (int) $wpdb->get_var(
					$wpdb->prepare(
						"SELECT COUNT(*) FROM {$enroll} WHERE class_id = %d AND enroll_id IS NOT NULL AND enroll_id <> ''",
						(int) $row->class_id
					)
				); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared -- table name from sp_table().
			}

			++$per_class[ $row->class_id ];

			$wpdb->update(
				$enroll,
				array( 'enroll_id' => sprintf( '%s-%03d', $base, $per_class[ $row->class_id ] ) ),
				array( 'id' => (int) $row->id ),
				array( '%s' ),
				array( '%d' )
			);

			++$updated;
		}
	}

	return $updated > 0 ? $updated : 0;
}

/**
 * Whether a table exists on this site.
 *
 * @param string $table Full table name including prefix.
 * @return bool
 */
function sp_table_exists( $table ) {
	global $wpdb;

	$found = $wpdb->get_var( $wpdb->prepare( 'SHOW TABLES LIKE %s', $table ) );

	return ( $found === $table );
}


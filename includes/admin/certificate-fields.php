<?php
/**
 * Certificate field definitions.
 *
 * The field list is configuration, not data: it decides what the issue form on
 * the Results screen asks for and what gets stored on the portal's certificate
 * record (and pushed to the Certificate Manager). Each field has a label, a
 * type, an optional auto-fill source and a required flag. The certificate's
 * visual design itself belongs to the Certificate Manager plugin.
 *
 * @package StudentPortal
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Certificate fields screen.
 */
function sp_admin_page_sp_certificate_fields() {
	$fields  = sp_certificate_fields();
	$sources = sp_certificate_field_sources();
	$types   = sp_certificate_field_types();
	?>
	<p class="sp-admin-muted">
		These fields become the form on the Results screen; the values are stored on the portal's
		certificate record. The certificate itself (layout, QR code, PDF) is generated by the
		Certificate Manager plugin. Anything with an auto-fill source arrives pre-filled from the
		student's data and can still be overwritten; anything without arrives blank. Required fields
		must be filled before a certificate can be issued.
	</p>

	<form method="post">
		<?php sp_admin_nonce_field( 'save_certificate_fields' ); ?>

		<div class="sp-table-wrap">
		<table class="widefat striped" id="sp-cert-fields">
			<thead>
				<tr>
					<th>Label</th>
					<th>Type</th>
					<th>Auto-fill from</th>
					<th>Required</th>
					<th></th>
				</tr>
			</thead>
			<tbody>
				<?php if ( ! $fields ) : ?>
					<tr class="sp-cert-fields-empty"><td colspan="5">No fields yet — add one below.</td></tr>
				<?php endif; ?>

				<?php foreach ( $fields as $sp_index => $sp_field ) : ?>
					<tr>
						<td>
							<input type="text" name="sp_cert_fields[<?php echo esc_attr( $sp_index ); ?>][label]"
								value="<?php echo esc_attr( isset( $sp_field['label'] ) ? $sp_field['label'] : '' ); ?>"
								class="regular-text" required />
							<input type="hidden" name="sp_cert_fields[<?php echo esc_attr( $sp_index ); ?>][key]"
								value="<?php echo esc_attr( isset( $sp_field['key'] ) ? $sp_field['key'] : 'field_' . ( $sp_index + 1 ) ); ?>" />
						</td>
						<td>
							<select name="sp_cert_fields[<?php echo esc_attr( $sp_index ); ?>][type]">
								<?php foreach ( $types as $sp_type_key => $sp_type_label ) : ?>
									<option value="<?php echo esc_attr( $sp_type_key ); ?>"
										<?php selected( isset( $sp_field['type'] ) ? $sp_field['type'] : 'text', $sp_type_key ); ?>>
										<?php echo esc_html( $sp_type_label ); ?>
									</option>
								<?php endforeach; ?>
							</select>
						</td>
						<td>
							<select name="sp_cert_fields[<?php echo esc_attr( $sp_index ); ?>][source]">
								<?php foreach ( $sources as $sp_source_key => $sp_source_label ) : ?>
									<option value="<?php echo esc_attr( $sp_source_key ); ?>"
										<?php selected( isset( $sp_field['source'] ) ? $sp_field['source'] : '', $sp_source_key ); ?>>
										<?php echo esc_html( $sp_source_label ); ?>
									</option>
								<?php endforeach; ?>
							</select>
						</td>
						<td>
							<input type="checkbox" name="sp_cert_fields[<?php echo esc_attr( $sp_index ); ?>][required]" value="1"
								<?php checked( ! empty( $sp_field['required'] ) ); ?> />
						</td>
						<td><button type="submit" class="button button-small sp-cert-fields-remove">Remove</button></td>
					</tr>
				<?php endforeach; ?>
			</tbody>
		</table>
		</div>

	<p>
		<button type="button" class="button" id="sp-add-cert-field">Add another field</button>
	</p>

	<?php submit_button( 'Save certificate fields' ); ?>
	</form>

	<form method="post" onsubmit="return confirm('Replace the field list with the default set? Issued certificates keep their stored values.');">
		<?php sp_admin_nonce_field( 'reset_certificate_fields' ); ?>
		<?php submit_button( 'Reset to the default field list', 'secondary' ); ?>
	</form>

	<script>
	( function () {
		var add    = document.getElementById( 'sp-add-cert-field' );
		var body   = document.querySelector( '#sp-cert-fields tbody' );
		var next   = <?php echo (int) count( $fields ); ?>;
		var source = <?php echo wp_json_encode( $sources ); ?>;
		var types  = <?php echo wp_json_encode( $types ); ?>;

		if ( ! add || ! body ) {
			return;
		}

		function options( map, selected ) {
			var html = '';

			Object.keys( map ).forEach( function ( key ) {
				html += '<option value="' + key.replace( /"/g, '&quot;' ) + '"'
					+ ( key === selected ? ' selected' : '' ) + '>'
					+ map[ key ].replace( /</g, '&lt;' ) + '</option>';
			} );

			return html;
		}

		add.addEventListener( 'click', function () {
			var row = document.createElement( 'tr' );
			var i   = next++;

			row.innerHTML = '<td><input type="text" name="sp_cert_fields[' + i + '][label]" class="regular-text" required />'
				+ '<input type="hidden" name="sp_cert_fields[' + i + '][key]" value="field_' + ( i + 1 ) + '" /></td>'
				+ '<td><select name="sp_cert_fields[' + i + '][type]">' + options( types, 'text' ) + '</select></td>'
				+ '<td><select name="sp_cert_fields[' + i + '][source]">' + options( source, '' ) + '</select></td>'
				+ '<td><input type="checkbox" name="sp_cert_fields[' + i + '][required]" value="1" /></td>'
				+ '<td><button type="button" class="button button-small sp-cert-fields-remove">Remove</button></td>';

			body.appendChild( row );
		} );

		body.addEventListener( 'click', function ( event ) {
			if ( event.target.classList.contains( 'sp-cert-fields-remove' ) ) {
				event.preventDefault();
				event.target.closest( 'tr' ).remove();
			}
		} );
	} )();
	</script>
	<?php
}
